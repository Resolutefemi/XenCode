package com.xencode.feature.agent.data.local.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.xencode.feature.agent.presentation.AgentAttachment
import com.xencode.feature.agent.presentation.BACKGROUND_NOTIFICATION_PREFIX
import com.xencode.feature.agent.presentation.COMPACTION_FAILURE_TOOL_NAME
import com.xencode.feature.agent.presentation.LEGACY_BACKGROUND_NOTIFICATION_PREFIX
import com.xencode.feature.agent.presentation.LEGACY_COMPACTION_FAILURE_TOOL_NAME
import com.xencode.feature.agent.presentation.MessageRole
import com.xencode.feature.agent.presentation.AgentUIMessage
import kotlinx.serialization.decodeFromString
import kotlinx.serialization.json.Json

@Entity(
    tableName = "agent_messages",
    indices = [Index(value = ["sessionId"])]
)
data class AgentMessageEntity(
    @PrimaryKey val id: String,
    val sessionId: String,
    val role: String,
    val content: String,
    val timestamp: Long,
    // ASSISTANT rows only: structured tool_calls (a Json-encoded List<ToolCall>); null when there are no tool calls.
    val toolCallsJson: String? = null,
    // TOOL rows only: the id of the corresponding assistant tool_use, used to rebuild valid pairs during replay.
    val toolCallId: String? = null,
    // TOOL rows only: tool name, used for UI rendering.
    val toolName: String? = null,
    // TOOL rows only: the arguments passed in this call (argsPreview, JSON text), shown in the UI as the "executed command".
    val toolArgs: String? = null,
    // TOOL rows only: whether the tool failed, used to render the status dot in the UI (green/red).
    val isError: Boolean = false,
    // ASSISTANT rows only: the model's reasoning for this turn. Persisted for UI display; sent back verbatim with the signature when Anthropic thinking is enabled. Null if absent.
    val reasoning: String? = null,
    // ASSISTANT rows only: the encrypted signature for Anthropic extended thinking. Sent back together with reasoning (required in the tool loop), otherwise a 400. Null for other providers.
    val signature: String? = null,
    // USER rows only: display metadata for user-uploaded attachments. The internal model prompt still never lands in content.
    val attachmentsJson: String? = null,
    /** This message has been folded into a summary by context compaction and should no longer take part in context replay or UI display. Defaults to false. */
    val isCompacted: Boolean = false,
    /** Internal summary generated by context compaction: takes part in model replay but is not shown as a normal chat bubble. */
    val isContextSummary: Boolean = false,
    /** Internal user anchor generated by context compaction: takes part in model replay, rendered in the UI as a compaction divider. */
    val isCompactionMarker: Boolean = false,
    val inputTokens: Int = 0,
    val outputTokens: Int = 0,
    // ASSISTANT rows only: a verbatim snapshot of Anthropic thinking / redacted_thinking content blocks (JSON array text).
    // The docs require these blocks to be sent back unmodified and in order, so the original blocks are stored instead of split fields (redacted data cannot be rebuilt).
    // Position is at the end: backup DTO mapping is positional, and inserting in the middle would shift it.
    val thinkingBlocksJson: String? = null,
    // ASSISTANT rows only: tokens of this turn's input that hit the server-side cache; the UI uses this to show the cache hit rate. Also append-only at the end.
    val cachedInputTokens: Int = 0,
    @ColumnInfo(defaultValue = "0")
    val isContextExcluded: Boolean = false,
    val compactedBySummaryId: String? = null
) {
    fun toUIMessage(): AgentUIMessage {
        val roleEnum = MessageRole.valueOf(role)
        return AgentUIMessage(
            id = id,
            role = roleEnum,
            content = content,
            timestamp = timestamp,
            toolName = toolName,
            toolArgs = toolArgs,
            isError = isError,
            reasoning = reasoning,
            attachments = decodeAttachments(attachmentsJson),
            isCompactionMarker = isCompactionMarker,
            isContextSummary = isContextSummary,
            isCompactionFailure = roleEnum == MessageRole.TOOL &&
                (toolName == COMPACTION_FAILURE_TOOL_NAME || toolName == LEGACY_COMPACTION_FAILURE_TOOL_NAME),
            isBackgroundNotification = roleEnum == MessageRole.USER &&
                (content.startsWith(BACKGROUND_NOTIFICATION_PREFIX) ||
                    content.startsWith(LEGACY_BACKGROUND_NOTIFICATION_PREFIX)),
            inputTokens = inputTokens,
            outputTokens = outputTokens,
            cachedInputTokens = cachedInputTokens
        )
    }

    private fun decodeAttachments(value: String?): List<AgentAttachment> {
        if (value.isNullOrBlank()) return emptyList()
        return runCatching { json.decodeFromString<List<AgentAttachment>>(value) }.getOrDefault(emptyList())
    }

    private companion object {
        val json = Json { ignoreUnknownKeys = true }
    }
}
