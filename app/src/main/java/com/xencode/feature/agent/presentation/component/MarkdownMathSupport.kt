/**
 * Math-aware [ImageTransformer]: recognizes the math links generated by [MarkdownPreprocessor] and renders them to bitmaps with jlatexmath;
 * all other (ordinary image) links are delegated to [delegate].
 *
 * @param delegate Downstream transformer for non-math image links (usually the local image renderer or NoOp).
 * @param baseTextSizeSp Base font size (sp) for inline formulas, aligned with the body text size around them.
 */
/**
 * Process-wide cache of formula layout sizes. Measuring requires building a [JLatexMathDrawable] (TeX parsing + layout),
 * heavy work on the main thread. Formula items scrolled out of a LazyColumn viewport get disposed; with only the
 * remember cache inside the Composable, scrolling back re-composes and re-measures — repeated in/out during a fast fling means repeated layout and jank.
 * This process-wide cache keyed by (latex, textSizePx) lays out and measures each formula only once.
 */
private const val TAG = "MarkdownMath"

private object LatexMeasureCache {
    private data class Key(val latex: String, val textSizePx: Float)

    // The cap is set high: each entry stores just one android.util.Size (two ints), negligible memory; but when flinging fast through
    // long history, too small a cap evicts old formulas and forces main-thread re-layout on scrolling back. 512 comfortably covers typical sessions.
    private const val MAX = 512
    private val sizes = object : LinkedHashMap<Key, android.util.Size>(MAX, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<Key, android.util.Size>?): Boolean = size > MAX
    }

    fun peek(latex: String, textSizePx: Float): android.util.Size? =
        synchronized(sizes) { sizes[Key(latex, textSizePx)] }

    fun put(latex: String, textSizePx: Float, size: android.util.Size) {
        synchronized(sizes) { sizes[Key(latex, textSizePx)] = size }
    }

    fun getOrMeasure(latex: String, textSizePx: Float, measure: () -> android.util.Size): android.util.Size =
        synchronized(sizes) {
            val key = Key(latex, textSizePx)
            // Building the drawable synchronously on the main thread just for the size is heavy (measured 20-113ms per complex formula). Normally the cache is already
            // filled by background prewarm (renderLatex writes back to the measure cache on completion) and hits directly; the synchronous fallback runs only when prewarm has not reached it yet.
            sizes[key] ?: measure().also { sizes[key] = it }
        }
}

private object LatexBitmapCache {
    private data class Key(
        val link: String,
        val colorArgb: Int,
        val textSizePx: Float,
    )

    // Concurrency limit: JLatexMathDrawable.build (TeX layout) is CPU-hungry. Prewarm can submit a hundred-plus renders at once;
    // dumping them straight onto Dispatchers.Default (thread count = core count) saturates the pool: a single render measured at 250ms+,
    // and the Markdown parsing/code highlighting sharing Default gets starved, while CPU saturation drags the main/render thread into dropped frames.
    // Capped at 2 concurrent: formulas appear progressively without hogging all the CPU.
    @OptIn(kotlinx.coroutines.ExperimentalCoroutinesApi::class)
    private val renderDispatcher = Dispatchers.Default.limitedParallelism(2)
    private val scope = CoroutineScope(SupervisorJob() + renderDispatcher)
    private const val MAX = 256
    private val bitmaps = object : LinkedHashMap<Key, Deferred<Bitmap?>>(MAX, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<Key, Deferred<Bitmap?>>?): Boolean = size > MAX
    }
    fun getOrStartBitmap(
        link: String,
        colorArgb: Int,
        textSizePx: Float,
        render: suspend () -> Bitmap?
    ): Deferred<Bitmap?> = synchronized(bitmaps) {
        val key = Key(link, colorArgb, textSizePx)
        bitmaps[key] ?: scope.async { render() }.also { deferred ->
            bitmaps[key] = deferred
            deferred.invokeOnCompletion {
                if (deferred.getCompletionExceptionOrNull() != null) {
                    synchronized(bitmaps) {
                        if (bitmaps[key] === deferred) bitmaps.remove(key)
                    }
                }
            }
        }
    }

    /** Prewarm: only starts the background render (writing the cache), without waiting for the result. Skips if already cached. */
    fun prewarm(link: String, colorArgb: Int, textSizePx: Float, render: suspend () -> Bitmap?) {
        getOrStartBitmap(link, colorArgb, textSizePx, render)
    }
}

internal class MathImageTransformer(
    private val delegate: ImageTransformer,
    private val baseTextSizeSp: Float,
) : ImageTransformer {

    // Override the placeholder size: the real root cause of upward-scroll stutter. The library's default placeholderConfig, when the image's real size is unknown (first frame),
    // gives a 200dp square (or a container-bounded square) placeholder; a formula's real height is only about 50dp, and once rendering completes
    // the placeholder collapses from 200dp to the real height — during upward scrolling this shrink happens above the viewport and triggers LazyColumn's top anchor compensation,
    // seen as "dragging back/stuttering". We already have the formula's real size (LatexMeasureCache), so return the exact placeholder; the placeholder equals
    // the final height from the very first frame, so upward scrolling no longer compensates. Non-formula links go to the delegate.
    override fun placeholderConfig(
        link: String,
        density: androidx.compose.ui.unit.Density,
        containerSize: androidx.compose.ui.geometry.Size,
        imageWidth: com.mikepenz.markdown.model.ImageWidth,
        imageSize: androidx.compose.ui.geometry.Size,
        imageSizeChanged: ((link: String, androidx.compose.ui.geometry.Size) -> Unit)?,
    ): com.mikepenz.markdown.model.PlaceholderConfig {
        val spec = MarkdownPreprocessor.decodeMathLink(link)
            ?: return super.placeholderConfig(link, density, containerSize, imageWidth, imageSize, imageSizeChanged)
        val latex = spec.first
        val textSizePx = with(density) { baseTextSizeSp.sp.toPx() }
        val sizePx = LatexMeasureCache.getOrMeasure(latex, textSizePx) { measureLatex(latex, textSizePx) }
        val sizeDp = with(density) {
            androidx.compose.ui.geometry.Size(sizePx.width.toDp().value, sizePx.height.toDp().value)
        }
        return com.mikepenz.markdown.model.PlaceholderConfig(
            size = sizeDp,
            verticalAlign = androidx.compose.ui.text.PlaceholderVerticalAlign.Bottom,
        )
    }

    @Composable
    override fun transform(link: String): ImageData? {
        val spec = MarkdownPreprocessor.decodeMathLink(link) ?: return delegate.transform(link)
        val (latex, block) = spec

        val density = LocalDensity.current
        val colorArgb = LocalContentColor.current.toArgb()
        // Block formulas use the same font size as body text, avoiding needless enlargement of block formulas.
        val textSizePx = with(density) { baseTextSizeSp.sp.toPx() }
        // Fetch the real size synchronously on first composition; estimating from character length would make formulas vary in size and, when too wide,
        // start display from the middle. Once the size is fixed it is never replaced asynchronously, so LazyColumn anchors are never rewritten.
        val layoutSize = remember(link, textSizePx) {
            LatexMeasureCache.getOrMeasure(latex, textSizePx) { measureLatex(latex, textSizePx) }
        }
        val renderTask = remember(link, colorArgb, textSizePx) {
            LatexBitmapCache.getOrStartBitmap(link, colorArgb, textSizePx) {
                renderLatex(latex, textSizePx, colorArgb)
            }
        }
        val bitmap by produceState<Bitmap?>(initialValue = null, renderTask) {
            value = renderTask.await()
        }
        // Always use the same layout size before and after the bitmap completes. Otherwise the Markdown inline placeholder would
        // go from 0 height to the formula height, and during a fast fling every completed formula would rewrite LazyColumn's anchors.
        val painter = remember(bitmap, layoutSize) {
            FixedLatexPainter(bitmap?.asImageBitmap(), layoutSize.width, layoutSize.height)
        }
        val widthDp = with(density) { layoutSize.width.toDp() }
        val heightDp = with(density) { layoutSize.height.toDp() }

        val base = if (block) {
            Modifier.padding(vertical = 4.dp).horizontalScroll(rememberScrollState())
        } else {
            Modifier
        }
        return ImageData(
            painter = painter,
            modifier = base.then(Modifier.size(widthDp, heightDp)),
            contentScale = ContentScale.Fit,
        )
    }

    private fun measureLatex(latex: String, textSizePx: Float): android.util.Size {
        return try {
            val drawable = JLatexMathDrawable.builder(latex)
                .textSize(textSizePx)
                .padding(2)
                .build()
            android.util.Size(
                drawable.intrinsicWidth.coerceAtLeast(1),
                drawable.intrinsicHeight.coerceAtLeast(1)
            )
        } catch (e: Exception) {
            android.util.Size(textSizePx.roundToInt().coerceAtLeast(1), textSizePx.roundToInt().coerceAtLeast(1))
        }
    }
    private class FixedLatexPainter(
        private val bitmap: androidx.compose.ui.graphics.ImageBitmap?,
        widthPx: Int,
        heightPx: Int,
    ) : Painter() {
        override val intrinsicSize: Size = Size(widthPx.toFloat(), heightPx.toFloat())

        override fun DrawScope.onDraw() {
            bitmap?.let { image ->
                val scale = minOf(
                    size.width / image.width,
                    size.height / image.height,
                )
                val drawWidth = (image.width * scale).roundToInt().coerceAtLeast(1)
                val drawHeight = (image.height * scale).roundToInt().coerceAtLeast(1)
                drawImage(
                    image = image,
                    dstSize = IntSize(drawWidth, drawHeight),
                    dstOffset = androidx.compose.ui.unit.IntOffset(
                        ((size.width - drawWidth) / 2f).roundToInt(),
                        ((size.height - drawHeight) / 2f).roundToInt(),
                    ),
                )
            }
        }
    }

    companion object {
        /**
         * Prewarms every LaTeX formula in a processed markdown snippet on a background thread: extracts the math links and starts a
         * background render for each (writing the bitmap cache). When rendering completes it writes back to the measure cache, so later
         * main-thread getOrMeasure calls hit directly without building the drawable synchronously — the key to eliminating fling stutter (a single
         * main-thread measure measured up to 113ms). Skips if already cached.
         *
         * Called on the IO/Default thread; never blocks composition.
         */
        fun prewarm(processedMarkdown: String, textSizePx: Float, colorArgb: Int) {
            if (!processedMarkdown.contains("xencode-math-")) return
            // Extract the link from Markdown image links ![](xencode-math-xxx://enc)
            for (match in MATH_LINK_REGEX.findAll(processedMarkdown)) {
                val link = match.groupValues[1]
                val spec = MarkdownPreprocessor.decodeMathLink(link) ?: continue
                val latex = spec.first
                if (LatexMeasureCache.peek(latex, textSizePx) != null) continue
                LatexBitmapCache.prewarm(link, colorArgb, textSizePx) {
                    renderLatex(latex, textSizePx, colorArgb)
                }
            }
        }

        private val MATH_LINK_REGEX = Regex("""!\[]\((xencode-math-(?:block|inline)://[^)]+)\)""")

        private fun renderLatex(latex: String, textSizePx: Float, colorArgb: Int): Bitmap? {
            return try {
                val drawable = JLatexMathDrawable.builder(latex)
                    .textSize(textSizePx)
                    .color(colorArgb)
                    .padding(2)
                    .build()
                val w = drawable.intrinsicWidth.coerceAtLeast(1)
                val h = drawable.intrinsicHeight.coerceAtLeast(1)
                // Write back to the measure cache: since the background build already produced the real size, the main thread need not build again.
                LatexMeasureCache.put(latex, textSizePx, android.util.Size(w, h))
                val bitmap = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
                val canvas = Canvas(bitmap)
                drawable.setBounds(0, 0, w, h)
                drawable.draw(canvas)
                bitmap
            } catch (e: Exception) {
                FileLogger.w(TAG, "LaTeX rendering failed: $latex", e)
                null
            }
        }
    }
}
